"""Small opt-in periodic-task configuration emitter; scheduling stays in C++."""
import json
import re


def render_task_files(config: dict, selection: str, module_names: list[str]) -> dict[str, str]:
    task = config["tasks"].get(selection)
    if task is None:
        raise ValueError(f"selected task {selection!r} is not present in config")
    # First supported example has one owner for the entire selected assembly.
    # Do not suggest that CAN ports/RM groups can already be shared by workers.
    if set(task["owns_modules"]) != set(module_names):
        raise ValueError("selected task must own exactly the selected modules")
    if task["services"]:
        raise ValueError("periodic task generation does not yet bind communication services")
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)+", task["entry"]):
        raise ValueError("generated task entry must be a dotted identifier, e.g. app.chassis_cycle")
    if task["stack_bytes"] > 0xffffffff:
        raise ValueError("generated task stack_bytes must fit uint32")
    priority = {"low": "osPriorityLow", "normal": "osPriorityNormal", "high": "osPriorityHigh"}[task["priority"]]
    return {
        "robot_tasks.h": '''// Generated by mrctl. Edit config.yaml instead.
#pragma once
#ifdef __cplusplus
extern "C" {
#endif
// Call after osKernelInitialize, before osKernelStart. 1 = created; 0 = failure.
int MR_CreateConfiguredTask(void);
#ifdef __cplusplus
}
#endif
''',
        "robot_tasks.hpp": f'''// Generated by mrctl. Edit config.yaml instead.
#pragma once
#include "task/periodic_task.hpp"
namespace mr::generated {{
inline constexpr mr::task::PeriodicTaskConfig kTaskConfig{{
    {json.dumps(selection)}, {task['period_us']}u, {task['stack_bytes']}u, {priority}}};
inline constexpr const char* kTaskEntry = {json.dumps(task['entry'])};
}}  // namespace mr::generated
namespace mr::app {{
// Required project implementation. Unknown entry must return empty hooks.
mr::task::TaskHooks BindPeriodicTask(const char* entry);
}}  // namespace mr::app
''',
        "robot_tasks.cpp": '''// Generated by mrctl. Edit config.yaml instead.
#include "robot_tasks.h"
#include "robot_tasks.hpp"
namespace {
mr::task::PeriodicTask task;
}
extern "C" int MR_CreateConfiguredTask(void) {
  return task.Create(mr::generated::kTaskConfig,
                     mr::app::BindPeriodicTask(mr::generated::kTaskEntry)) ? 1 : 0;
}
''',
    }
